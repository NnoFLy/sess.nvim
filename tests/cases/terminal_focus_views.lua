local terminal = dofile(vim.env.SESS_TEST_REPO .. "/tests/helpers/terminal.lua")
terminal.run(function(t)
    local api = require("sess.api")
    local first = t.launch(t.probe_command("focus-view"))
    t.output(first, "READY-focus-view")
    local first_win = vim.api.nvim_get_current_win()
    vim.cmd("vsplit")
    local other = t.launch(t.probe_command("focus-other"))
    local ok, err, focused = api.terminal.focus(first.id)
    assert(ok, err)
    fixture.equal(first.bufnr, focused.bufnr)
    fixture.equal(first.job_id, focused.job_id)
    fixture.equal(first_win, vim.api.nvim_get_current_win())
    vim.api.nvim_win_close(first_win, false)
    ok, err, focused = api.terminal.focus(first.id)
    assert(ok, err)
    fixture.equal(first.bufnr, focused.bufnr)
    t.probe(focused, "focus-view", "existing-hidden-view")
    -- Neither labels nor a matching channel alone authorize reusing a view.
    vim.api.nvim_buf_set_name(first.bufnr, "adopted-view")
    ok, err, focused = api.terminal.focus(first.id)
    assert(ok, err)
    assert(focused.bufnr ~= first.bufnr)
    assert(vim.api.nvim_buf_is_valid(first.bufnr))
    t.probe(focused, "focus-view", "reconnect-after-rename")
    t.probe(other, "focus-other", "other-not-retargeted")
    local previous = focused
    local helper_id = assert(vim.api.nvim_buf_get_name(focused.bufnr):match("/([a-f0-9]+)$"))
    local sessions = t.tmux({ "list-sessions", "-F", "#{session_id}\t#{session_name}" })
    local helper_session = assert(sessions:match("(%$%d+)\tsess_h_" .. helper_id .. "\n"))
    t.tmux({ "set-option", "-t", helper_session, "@sess_helper", "unrelated" })
    ok, err, focused = api.terminal.focus(first.id)
    assert(ok, err)
    assert(focused.bufnr ~= previous.bufnr, "must not focus an unverified helper")
    assert(vim.api.nvim_buf_is_valid(previous.bufnr), "must not destroy an uncertain view")
    t.probe(focused, "focus-view", "reconnect-after-helper-change")
end)
