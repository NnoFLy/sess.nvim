#!/usr/bin/python3
"""Bounded native-only research. No packages, credentials, default tmux, or Sess."""
import hashlib
import json
import os
from pathlib import Path
import pty
import select
import shutil
import signal
import subprocess
import tempfile
import time

HERE = Path(__file__).resolve().parent
NVIM = "/usr/bin/nvim"
TMUX = "/usr/bin/tmux"
results = []


def check(case, got, expected):
    results.append(dict(id=case, status="pass" if got == expected else "fail",
                        got=got, expected=expected))


def wait_file(path):
    end = time.monotonic() + 4
    while time.monotonic() < end:
        if path.is_file():
            return
        time.sleep(.005)  # Poll a child-published barrier, never assume startup.
    raise RuntimeError("synthetic child barrier timed out: " + path.name)


def call(argv, env, **kwargs):
    return subprocess.run(argv, env=env, text=True, capture_output=True,
                          timeout=10, **kwargs)


def main(root):
    fixture = root / "shell recorder"
    shutil.copyfile(HERE / "fixture.py", fixture)
    fixture.chmod(0o700)
    for name in ("home", "config", "data", "state", "cache", "runtime", "global",
                 "tab", "window", "explicit"):
        (root / name).mkdir(mode=0o700)
    env = dict(PATH="/usr/bin:/bin", HOME=str(root / "home"),
               XDG_CONFIG_HOME=str(root / "config"), XDG_DATA_HOME=str(root / "data"),
               XDG_STATE_HOME=str(root / "state"), XDG_CACHE_HOME=str(root / "cache"),
               XDG_RUNTIME_DIR=str(root / "runtime"), TMPDIR=str(root),
               TERM="xterm-256color", LANG="C.UTF-8", PROBE_ROOT=str(root))
    version = call([NVIM, "--version"], env).stdout.splitlines()[:3]
    if version[0] != "NVIM v0.12.6":
        raise RuntimeError("blocked: /usr/bin/nvim is not pinned latest stable v0.12.6")
    print(json.dumps(dict(nvim=version,
                         nvim_sha256=hashlib.sha256(Path(NVIM).read_bytes()).hexdigest(),
                         tmux=call([TMUX, "-S", str(root / "server.sock"), "-V"], env).stdout.strip())))
    native = call([NVIM, "--headless", "-u", "NONE", "-i", "NONE", "--noplugin", "-n",
                   "-l", str(HERE / "native.lua")], env, cwd=root)
    if native.returncode != 0 or not (root / "native-results.json").exists():
        raise RuntimeError("native harness failed: " + native.stderr[:1000])
    results.extend(json.loads((root / "native-results.json").read_text()))

    # Separate real editor UI PTY: keyboard bytes, not headless mode or chansend.
    master, slave = pty.openpty()
    ui_env = dict(env, PROBE_OUT=str(root / "ui-child.json"))
    ui = subprocess.Popen(
        [NVIM, "-u", "NONE", "-i", "NONE", "--noplugin", "-n",
         "-c", "terminal /bin/sh", "-c", "startinsert", "-c",
         "lua vim.defer_fn(function() vim.fn.writefile({vim.api.nvim_get_mode().mode}, vim.env.PROBE_ROOT..'/ui.ready') end, 30)"],
        env=ui_env, cwd=root, stdin=slave, stdout=slave, stderr=slave,
        start_new_session=True)
    os.close(slave)
    try:
        wait_file(root / "ui.ready")
        check("PTY-real-editor-terminal-input-mode", (root / "ui.ready").read_text().strip(), "t")
        # Fixture path is trusted, generated by mkdtemp (no quote character).
        os.write(master, ("'" + str(fixture) + "'\n").encode())
        wait_file(root / "ui-child.json")
        child = json.loads((root / "ui-child.json").read_text())
        check("PTY-real-editor-keyboard-reaches-shell", child["tty"], [True] * 3)
        os.write(master, b"\x1c\x0e:qa!\r")
        ui.wait(timeout=4)
        check("PTY-real-editor-clean-exit", ui.returncode, 0)
    finally:
        if ui.poll() is None:
            os.killpg(ui.pid, signal.SIGKILL)
            ui.wait()
        # Synthetic UI output only; discard, bounded to 64 KiB.
        if select.select([master], [], [], 0)[0]:
            try:
                os.read(master, 65536)
            except OSError:
                pass
        os.close(master)

    socket = str(root / "server.sock")
    config = root / "tmux.conf"
    config.write_text("set -g default-shell /bin/sh\nset -g update-environment ''\n"
                      "set -s exit-empty off\nset -g remain-on-exit on\n")
    server_env = dict(env, PROBE_VALUE="old-server", PROBE_DROP="old-server-only")
    caller_env = dict(env, PROBE_VALUE="fresh-invoker", TMUX="synthetic-outer", TMUX_PANE="%999")

    def tmux(*args, startup=False):
        prefix = [TMUX, "-S", socket, "-f", str(config)]
        if not startup:
            prefix.append("-N")
        return call(prefix + list(args), server_env if startup else caller_env, cwd=root)

    started = False
    seq = 0

    def spawn(argv, extra=(), cwd=None):
        nonlocal seq
        seq += 1
        out = root / ("tmux-" + str(seq) + ".json")
        command = ["new-window", "-d", "-t", anchor + ":", "-c", str(cwd or root),
                   "-e", "PROBE_OUT=" + str(out), *extra, "--", *argv]
        proc = tmux(*command)
        if proc.returncode:
            return proc, None
        wait_file(out)
        return proc, json.loads(out.read_text())

    try:
        init = tmux("new-session", "-d", "-P", "-F", "#{session_id}", "-s", "synthetic",
                    "/bin/sleep", "60", startup=True)
        if init.returncode:
            raise RuntimeError("private tmux initialization failed: " + init.stderr[:500])
        started = True
        anchor = init.stdout.strip()
        assert anchor.startswith("$") and anchor[1:].isdigit()
        literals = ["", "%", "#", "$PROBE_VALUE", "~", "a b", "'\"\\", "|", ";",
                    "ends;", "slash\\;", "#{pane_id}", "#(false)", "\n"]
        # tmux's argv command separator parser still runs; direct exec is not enough.
        raw, _ = spawn([str(fixture), ";", "not-a-tmux-command"])
        check("TMUX-raw-semicolon-negative-control", raw.returncode != 0, True)
        # cmd-parse.y unescapes one backslash immediately before a final semicolon.
        # This is a disposable known-fixture encoding, not a general Sess adapter.
        encoded = [s[:-1] + "\\;" if s.endswith(";") else s for s in literals]
        proc, data = spawn([str(fixture), *encoded])
        check("TMUX-direct-argv-literals-parser-escaped", data["argv"], literals)
        check("TMUX-real-workload-PTY", data["tty"], [True] * 3)
        # Forward the native-observed shell argv, without inventing tokenization.
        native_shell = next(r["got"] for r in results if r["id"] == "SHELL-double-quote-tokenization-shellquote-ignored")
        _, forwarded = spawn([str(fixture), *native_shell])
        check("TMUX-native-observed-shell-vector", forwarded["argv"], native_shell)
        check("TMUX-old-server-environment-negative-control", data["env"]["PROBE_VALUE"], "old-server")
        check("TMUX-inner-routing-replaces-outer", [data["env"]["TMUX"] != "synthetic-outer",
                                                    data["env"]["TMUX_PANE"] != "%999"], [True, True])
        _, data = spawn([str(fixture), "override"], ("-e", "PROBE_VALUE=per-workload"), root / "explicit")
        check("TMUX-cwd-explicit", data["cwd"], str(root / "explicit"))
        check("TMUX-per-workload-override", data["env"]["PROBE_VALUE"], "per-workload")
        _, data = spawn([str(fixture), "unchanged"])
        check("TMUX-other-workload-env-unchanged", data["env"]["PROBE_VALUE"], "old-server")
        # Native tmux falls back on chdir failure. The future API must not do that.
        _, data = spawn([str(fixture), "invalid-cwd"], cwd=root / "missing")
        check("TMUX-invalid-cwd-falls-back-negative-control", data["cwd"], str(root / "home"))
        format_dir = root / "#{session_name}"
        format_dir.mkdir()
        _, data = spawn([str(fixture), "format-cwd"], cwd=format_dir)
        check("TMUX-cwd-format-expansion-negative-control", data["cwd"], str(root / "home"))
        _, data = spawn([str(fixture), "literal-cwd"], cwd=str(format_dir).replace("#", "##"))
        check("TMUX-cwd-format-escaped-literal", data["cwd"], str(format_dir))
        # Deterministic preflight/spawn race point: remove a once-valid directory.
        raced = root / "once-valid"
        raced.mkdir()
        check("CWD-race-preflight-valid", raced.is_dir(), True)
        raced.rename(root / "moved-directory")
        _, data = spawn([str(fixture), "raced-cwd"], cwd=raced)
        check("TMUX-cwd-disappears-after-preflight-negative-control", data["cwd"], str(root / "home"))
        # GNU env's child-side chdir is fail-closed for the same missing path.
        failed_out = root / "failed-cwd.json"
        proc = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":", "--",
                    "/usr/bin/env", "-C", str(raced), "-i", "PROBE_OUT=" + str(failed_out), str(fixture))
        pane = proc.stdout.strip()
        assert proc.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        end = time.monotonic() + 4
        dead = ""
        while time.monotonic() < end:
            dead = tmux("display-message", "-p", "-t", pane, "#{pane_dead}:#{pane_dead_status}").stdout.strip()
            if dead.startswith("1:"):
                break
        check("TMUX-env-C-fails-closed-at-child-boundary", [dead, failed_out.exists()], ["1:125", False])
        # Real tmux PTY startup/input with a child readiness barrier.
        input_out = root / "tmux-input.json"
        proc = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":",
                    "-e", "PROBE_OUT=" + str(input_out), "-e", "PROBE_READ=1", "--", str(fixture), "read")
        pane = proc.stdout.strip()
        assert proc.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        wait_file(input_out.with_suffix(".ready"))
        sent = tmux("send-keys", "-t", pane, "-l", "synthetic-tmux-input")
        enter = tmux("send-keys", "-t", pane, "Enter")
        wait_file(input_out)
        data = json.loads(input_out.read_text())
        check("TMUX-PTY-startup-input", [sent.returncode, enter.returncode, data["tty"], data["input"]],
              [0, 0, [True] * 3, "synthetic-tmux-input"])
        # env -i executes one executable argv directly even though tmux's one-arg
        # form invokes $SHELL -c. Full synthetic env also discards stale variables.
        seq += 1
        out = root / ("env-" + str(seq) + ".json")
        # Explicit command below gives the same output path to env -i and the oracle.
        proc = tmux("new-window", "-d", "-t", anchor + ":", "-c", str(root), "--",
                    "/usr/bin/env", "-i", "PROBE_OUT=" + str(out), "PROBE_VALUE=fresh-invoker",
                    "PROBE_KEEP=explicit-only", str(fixture))
        check("TMUX-env-i-launch", proc.returncode, 0)
        wait_file(out)
        data = json.loads(out.read_text())
        check("TMUX-env-i-fresh-not-server", data["env"], {"PROBE_VALUE": "fresh-invoker", "PROBE_KEEP": "explicit-only"})
        check("TMUX-env-i-single-executable-argv", data["argv"], [])
        # env -i assignment argv is NOT a secret-retention-safe launch recipe:
        # tmux retains pane argv after env has exec'd the workload.
        # new-window -d does not select the new pane; obtain its exact pane ID
        # with -P on a separate synthetic sample.
        retained_out = root / "retention.json"
        created = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":", "--",
                       "/usr/bin/env", "-i", "PROBE_OUT=" + str(retained_out),
                       "PROBE_VALUE=synthetic-not-secret", str(fixture))
        pane = created.stdout.strip()
        assert created.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        wait_file(retained_out)
        retained = tmux("display-message", "-p", "-t", pane, "#{pane_start_command}")
        check("TMUX-env-i-retains-assignment-negative-control", "PROBE_VALUE=synthetic-not-secret" in retained.stdout, True)
        # A bare -e key is silently ignored, not unset. This is a negative control.
        # No environment assignments are part of workload argv in this candidate.
        private_out = root / "per-workload-env.json"
        created = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":",
                       "-e", "PROBE_OUT=" + str(private_out), "-e", "PROBE_VALUE=fresh-override",
                       "-e", "PROBE_DROP", "--", "/usr/bin/env", "--", str(fixture))
        pane = created.stdout.strip()
        assert created.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        wait_file(private_out)
        private_data = json.loads(private_out.read_text())
        check("TMUX-e-bare-key-does-not-unset-negative-control", [private_data["env"].get("PROBE_DROP"), private_data["env"]["PROBE_VALUE"], private_data["argv"]], ["old-server-only", "fresh-override", []])
        retained = tmux("display-message", "-p", "-t", pane, "#{pane_start_command}")
        check("TMUX-e-not-in-workload-command", "fresh-override" in retained.stdout, False)
        removed_out = root / "per-workload-remove.json"
        created = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":",
                       "-e", "PROBE_OUT=" + str(removed_out), "-e", "PROBE_VALUE=fresh-with-unset",
                       "--", "/usr/bin/env", "-u", "PROBE_DROP", "--", str(fixture))
        pane = created.stdout.strip()
        assert created.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        wait_file(removed_out)
        removed = json.loads(removed_out.read_text())
        check("TMUX-e-plus-env-u-fresh-values-and-removal", [removed["env"].get("PROBE_DROP"), removed["env"]["PROBE_VALUE"], removed["argv"]], [None, "fresh-with-unset", []])
        retained = tmux("display-message", "-p", "-t", pane, "#{pane_start_command}")
        check("TMUX-e-plus-env-u-no-assignment-in-command", "fresh-with-unset" in retained.stdout, False)
        # A later invocation on the same old server must get its own fresh values.
        out2 = root / "env-second.json"
        proc = tmux("new-window", "-d", "-t", anchor + ":", "--", "/usr/bin/env", "-i",
                    "PROBE_OUT=" + str(out2), "PROBE_VALUE=second-invoker", str(fixture))
        wait_file(out2)
        data2 = json.loads(out2.read_text())
        check("TMUX-env-i-second-invocation-fresh", [proc.returncode, data2["env"]], [0, {"PROBE_VALUE": "second-invoker"}])
        _, data = spawn(["/bin/sh", "-c", "printf 'synthetic-pipe\\n' | PROBE_READ=1 '" + str(fixture) + "'"])
        check("TMUX-real-shell-pipeline", data["input"], "synthetic-pipe")
        # tmux interprets a single empty command as an empty pane, not shell -c ''.
        proc = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":", "--", "")
        pane = proc.stdout.strip()
        assert proc.returncode == 0 and pane.startswith("%") and pane[1:].isdigit()
        empty = tmux("display-message", "-p", "-t", pane, "#{pane_pid}|#{pane_dead}").stdout.strip()
        check("TMUX-empty-command-is-no-process-negative-control", empty, "|0")
        # Negative control: a lone executable pathname containing spaces is shell text.
        proc = tmux("new-window", "-d", "-P", "-F", "#{pane_id}", "-t", anchor + ":", "-e", "PROBE_OUT=" + str(root / "one.json"),
                    "--", str(fixture))
        check("TMUX-one-argument-accepted-not-direct", proc.returncode, 0)
        pane = proc.stdout.strip()
        assert pane.startswith("%") and pane[1:].isdigit()
        # Query pane_dead is an exit barrier, not a sleep-based absence assertion.
        end = time.monotonic() + 4
        dead = ""
        while time.monotonic() < end:
            dead = tmux("display-message", "-p", "-t", pane, "#{pane_dead}").stdout.strip()
            if dead == "1":
                break
        check("TMUX-one-argument-shell-parse-negative-control", [dead, (root / "one.json").exists()], ["1", False])
    finally:
        if started:
            # Only this harness's private socket/server/synthetic jobs can be reached.
            tmux("kill-server")


if __name__ == "__main__":
    os.umask(0o077)
    with tempfile.TemporaryDirectory(prefix="sess-nvim-semantics-") as temp:
        root = Path(temp)
        try:
            main(root)
        except Exception as exc:
            results.append(dict(id="HARNESS", status="fail", error=str(exc)))
        # No real environment or pane contents. Normalize the disposable pathname.
        for result in results:
            print(json.dumps(result, sort_keys=True).replace(str(root), "<root>"))
        passed = sum(r["status"] == "pass" for r in results)
        print(f"SUMMARY pass={passed} fail={len(results) - passed}")
        raise SystemExit(0 if passed == len(results) and results else 1)
